#!/usr/bin/env node
// Builds every harness form of the design-engineering subagents from the
// canonical Claude Code files in agents/*.md (the single source of truth):
//
//   agent/subagents/<name>/{agent.ts,instructions.md}   eve twins
//   harness/codex/agents/<name>.toml                    Codex custom agents
//   harness/opencode/agents/<name>.md                   OpenCode subagents
//   harness/gemini/agents/<name>.md                     Gemini CLI subagents
//   harness/cursor/agents/<name>.md                     Cursor subagents
//   harness/README.md                                   install table
//
//   node scripts/build-agents.mjs           write the output
//   node scripts/build-agents.mjs --check   exit 1 if anything is stale (CI)
//
// Output is deterministic: sources are read in sorted order, CRLF is
// normalised to LF, and nothing depends on the clock or the platform.
// An eve twin file whose first line contains "build-agents: keep" is
// hand-written and left alone (for a subagent that needs more than the
// generated agent.ts, such as nested council members).

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, rmdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const SRC = join(ROOT, "agents");
const EVE = join(ROOT, "agent", "subagents");
const HARNESS = join(ROOT, "harness");
const KEEP = "build-agents: keep";
const GEN = "Generated by scripts/build-agents.mjs";
const SOUL_URL = "https://github.com/AgentsORG/design-engineering/blob/main/SOUL.md";
const EVE_SKILL = "$HOME/.agents/skills/design-engineering/";

// Claude Code model alias -> AI Gateway id for eve.
const EVE_MODEL = {
  sonnet: "anthropic/claude-sonnet-5.5",
  opus: "anthropic/claude-opus-5.5",
  haiku: "anthropic/claude-haiku-5",
  inherit: "anthropic/claude-opus-5.5",
};
const EFFORT = { low: "low", medium: "medium", high: "high", xhigh: "xhigh", max: "xhigh" };
const WRITE_TOOLS = ["Edit", "Write", "Bash", "NotebookEdit"];
const GEMINI_TOOLS = {
  Read: ["read_file", "read_many_files"],
  Grep: ["grep_search"],
  Glob: ["glob", "list_directory"],
  Edit: ["replace"],
  Write: ["write_file"],
  Bash: ["run_shell_command"],
  WebFetch: ["web_fetch"],
  WebSearch: ["google_web_search"],
};

const lf = (s) => s.replace(/\r\n?/g, "\n");
const q = (s) => JSON.stringify(s);
const num = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, "_");

function fail(msg) {
  console.error(`build-agents: ${msg}`);
  process.exit(1);
}

// ---------------------------------------------------------------- parse

function parseAgent(file) {
  const text = lf(readFileSync(join(SRC, file), "utf8"));
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) fail(`${file}: missing YAML frontmatter`);
  const fm = {};
  for (const line of m[1].split("\n")) {
    if (!line.trim() || line.trim().startsWith("#")) continue;
    const kv = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (!kv) fail(`${file}: frontmatter line is not "key: value" (keep each field on one line): ${line}`);
    let v = kv[2].trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    fm[kv[1]] = v;
  }
  for (const k of ["name", "description", "tools", "model"]) if (!fm[k]) fail(`${file}: frontmatter needs ${k}`);
  if (fm.name !== file.replace(/\.md$/, "")) fail(`${file}: name "${fm.name}" must equal the file name`);
  if (!/^## Soul$/m.test(text)) fail(`${file}: needs a ## Soul section`);
  if (!/^## Skill root$/m.test(text)) fail(`${file}: needs a ## Skill root section`);
  if (!/^## Loop$/m.test(text)) fail(`${file}: needs a ## Loop section`);
  const body = text.slice(m[0].length).replace(/^\n+/, "").replace(/\n*$/, "\n");
  const tools = fm.tools.split(",").map((t) => t.trim()).filter(Boolean);
  const maxTurns = fm.maxTurns ? Number(fm.maxTurns) : 30;
  if (!Number.isInteger(maxTurns) || maxTurns < 1) fail(`${file}: maxTurns must be a positive integer`);
  if (fm.effort && !EFFORT[fm.effort]) fail(`${file}: effort must be one of ${Object.keys(EFFORT).join(", ")}`);
  if (!EVE_MODEL[fm.model] && !fm.model.includes("/")) fail(`${file}: no eve model for "${fm.model}"`);
  return {
    name: fm.name,
    description: fm.description,
    tools,
    model: fm.model,
    effort: fm.effort ? EFFORT[fm.effort] : null,
    maxTurns,
    readonly: !tools.some((t) => WRITE_TOOLS.includes(t)),
    body,
  };
}

// ---------------------------------------------------------------- body rewrites

function replaceSection(body, heading, section) {
  const re = new RegExp(`^## ${heading}\\n[\\s\\S]*?(?=^## )`, "m");
  return body.replace(re, () => section + "\n");
}

function skillRoot(dirs) {
  const list = dirs.map((d) => `\`${d}\``);
  const last = list.pop();
  return `## Skill root

Paths below are relative to the skill root: the first of ${list.join(", ")} or ${last} that holds a \`SKILL.md\`. Resolve it once, before the first read. If none exists, say so and stop rather than answer from memory.
`;
}

const HARNESS_ROOTS = {
  codex: ["./skills/design-engineering", "./.agents/skills/design-engineering", "~/.agents/skills/design-engineering", "~/.codex/skills/design-engineering"],
  opencode: ["./skills/design-engineering", "./.agents/skills/design-engineering", "~/.agents/skills/design-engineering", "~/.config/opencode/skills/design-engineering"],
  gemini: ["./skills/design-engineering", "./.agents/skills/design-engineering", "~/.agents/skills/design-engineering", "~/.gemini/skills/design-engineering"],
  cursor: ["./skills/design-engineering", "./.agents/skills/design-engineering", "~/.agents/skills/design-engineering", "~/.cursor/skills/design-engineering", "~/.claude/skills/design-engineering"],
};

function harnessBody(agent, harness) {
  let b = replaceSection(agent.body, "Skill root", skillRoot(HARNESS_ROOTS[harness]));
  return b.replaceAll("[SOUL.md](../SOUL.md)", `[SOUL.md](${SOUL_URL})`);
}

function eveBody(agent) {
  let b = replaceSection(
    agent.body,
    "Skill root",
    `## Skill root

The skill is seeded at \`${EVE_SKILL}\`, and every skill path below is spelled out under it. If it is missing, say so and stop rather than answer from memory.
`,
  );
  // Prefix root-relative skill paths: `references/...`, `scripts/...`, node scripts/...
  b = b.replace(/(^|[\s`(])((?:references|scripts)\/)/gm, (_, pre, dir) => pre + EVE_SKILL + dir);
  return b.replace(/Inherits from the repo-root \[SOUL\.md\]\([^)]*\)/g, "Inherits from the root agent's instructions");
}

// ---------------------------------------------------------------- emitters

function eveAgentTs(a) {
  const description = a.description.replace(/^Load when\b/, "Delegate when");
  const model = EVE_MODEL[a.model] ?? a.model;
  const lines = [
    `// ${GEN} from agents/${a.name}.md. Do not edit:`,
    "// change the source and run `npm run build:agents`.",
    'import { defineAgent } from "eve";',
    "",
    "export default defineAgent({",
    "  description:",
    `    ${q(description)},`,
    `  model: ${q(model)},`,
  ];
  if (a.effort) lines.push(`  reasoning: ${q(a.effort)},`);
  lines.push(
    "  limits: {",
    `    // Loop guard sized from maxTurns (${a.maxTurns}); the round budget itself is in instructions.md (## Loop).`,
    "    sessionUsage: ({ window }) =>",
    `      window.inputTokens - window.cacheReadTokens >= ${num(a.maxTurns * 50000)} ||`,
    `      window.outputTokens >= ${num(a.maxTurns * 4000)},`,
    "  },",
    "});",
    "",
  );
  return lines.join("\n");
}

function eveInstructions(a) {
  return `<!-- ${GEN} from agents/${a.name}.md. Edit that file, then run \`npm run build:agents\`. -->\n\n${eveBody(a)}`;
}

function tomlString(s) {
  if (!s.includes("'''")) return `'''\n${s}'''`;
  return `"""\n${s.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"')}"""`;
}

function codexToml(a) {
  const out = [
    `# ${GEN} from agents/${a.name}.md. Do not edit.`,
    `# Install: copy to ~/.codex/agents/ (personal) or .codex/agents/ (project).`,
    `name = ${q(a.name)}`,
    `description = ${q(a.description)}`,
  ];
  if (a.effort) out.push(`model_reasoning_effort = ${q(a.effort)}`);
  out.push(`developer_instructions = ${tomlString(harnessBody(a, "codex"))}`);
  if (a.readonly) out.push("", "[features]", "# Read-only reviewer: Codex agents inherit the sandbox, so drop the shell instead.", "shell_tool = false");
  return out.join("\n") + "\n";
}

function frontmatter(lines, body) {
  return `---\n${lines.join("\n")}\n---\n\n${body}`;
}

function opencodeMd(a) {
  const has = (...t) => t.some((x) => a.tools.includes(x));
  const perms = [
    ["read", true],
    ["glob", true],
    ["grep", true],
    ["skill", true],
    ["edit", has("Edit", "Write", "NotebookEdit")],
    ["shell", has("Bash")],
    ["subagent", has("Agent", "Task")],
    ["webfetch", has("WebFetch")],
    ["websearch", has("WebSearch")],
  ];
  const lines = [
    `# ${GEN} from agents/${a.name}.md. Do not edit.`,
    `description: ${q(a.description)}`,
    "mode: subagent",
    `steps: ${a.maxTurns}`,
    "permissions:",
  ];
  for (const [action, allow] of perms) {
    lines.push(`  - action: ${action}`, '    resource: "*"', `    effect: ${allow ? "allow" : "deny"}`);
  }
  return frontmatter(lines, harnessBody(a, "opencode"));
}

function geminiMd(a) {
  const tools = new Set();
  for (const t of a.tools) {
    const mcp = /^mcp__([^_]+(?:_[^_]+)*?)__/.exec(t);
    if (mcp) tools.add(`mcp_${mcp[1]}_*`);
    for (const g of GEMINI_TOOLS[t] ?? []) tools.add(g);
  }
  const lines = [
    `# ${GEN} from agents/${a.name}.md. Do not edit.`,
    `name: ${a.name}`,
    `description: ${q(a.description)}`,
    "kind: local",
    "tools:",
    ...[...tools].sort().map((t) => `  - ${t}`),
    "model: inherit",
    `max_turns: ${a.maxTurns}`,
    `timeout_mins: ${Math.min(30, Math.max(10, Math.ceil(a.maxTurns / 4)))}`,
  ];
  return frontmatter(lines, harnessBody(a, "gemini"));
}

function cursorMd(a) {
  const lines = [
    `# ${GEN} from agents/${a.name}.md. Do not edit.`,
    `name: ${a.name}`,
    `description: ${q(a.description)}`,
    "model: inherit",
    `readonly: ${a.readonly}`,
  ];
  return frontmatter(lines, harnessBody(a, "cursor"));
}

function harnessReadme(agents) {
  const rows = agents.map(
    (a) => `| \`${a.name}\` | ${a.readonly ? "read-only" : "writes"} | ${a.effort ?? "default"} | ${a.maxTurns} |`,
  );
  return `# Harness agents

${GEN} from \`agents/*.md\`. Do not edit these files: change the canonical agent, then run \`npm run build:agents\` (CI runs \`node scripts/build-agents.mjs --check\`).

Every agent resolves the design-engineering skill at runtime (its \`## Skill root\` section lists the folders it tries), so install the skill first: \`npx skills add AgentsORG/design-engineering\`.

| Harness | Files | Install to |
|---|---|---|
| Claude Code | \`agents/*.md\` (canonical) | the plugin (\`/plugin install design-engineering@agentsorg\`), \`~/.claude/agents/\` or \`.claude/agents/\` |
| Codex | \`harness/codex/agents/*.toml\` | \`~/.codex/agents/\` or \`.codex/agents/\` |
| OpenCode | \`harness/opencode/agents/*.md\` | \`~/.config/opencode/agents/\` or \`.opencode/agents/\` |
| Gemini CLI | \`harness/gemini/agents/*.md\` | \`~/.gemini/agents/\` or \`.gemini/agents/\` |
| Cursor | \`harness/cursor/agents/*.md\` | \`~/.cursor/agents/\` or \`.cursor/agents/\` (Cursor also reads \`.claude/agents/\`) |
| eve | \`agent/subagents/<name>/\` | ships with the eve runtime in \`agent/\` |

What the generator maps:

- **Model**: Claude Code keeps \`model\`; eve maps \`sonnet\` to \`${EVE_MODEL.sonnet}\` and \`opus\` to \`${EVE_MODEL.opus}\`; Codex, OpenCode, Gemini and Cursor inherit the session's model.
- **Effort**: \`effort\` becomes Codex \`model_reasoning_effort\` and eve \`reasoning\` (\`max\` maps to \`xhigh\`).
- **Turn cap**: \`maxTurns\` becomes OpenCode \`steps\`, Gemini \`max_turns\` and the eve \`limits.sessionUsage\` guard. Codex and Cursor have no per-agent cap; the \`## Loop\` budget in the body is the cap there.
- **Read-only**: an agent without Edit, Write or Bash gets Codex \`features.shell_tool = false\`, OpenCode \`edit\`/\`shell\` denied and Cursor \`readonly: true\`.
- **Tools**: Gemini gets its own tool names (\`read_file\`, \`grep_search\`, \`run_shell_command\` …); MCP tools become \`mcp_<server>_*\`.

| Agent | Access | Effort | Turn cap |
|---|---|---|---|
${rows.join("\n")}
`;
}

// ---------------------------------------------------------------- plan

const files = readdirSync(SRC)
  .filter((f) => f.endsWith(".md") && f.toLowerCase() !== "readme.md")
  .sort();
if (!files.length) fail("no agents found in agents/");
const agents = files.map(parseAgent);

const expected = new Map(); // repo-relative path -> content
const kept = [];
const put = (rel, content) => expected.set(rel.split("\\").join("/"), content);

for (const a of agents) {
  for (const [file, content] of [
    ["agent.ts", eveAgentTs(a)],
    ["instructions.md", eveInstructions(a)],
  ]) {
    const p = join(EVE, a.name, file);
    if (existsSync(p) && lf(readFileSync(p, "utf8")).split("\n", 1)[0].includes(KEEP)) {
      kept.push(relative(ROOT, p));
      continue;
    }
    put(relative(ROOT, p), content);
  }
  put(`harness/codex/agents/${a.name}.toml`, codexToml(a));
  put(`harness/opencode/agents/${a.name}.md`, opencodeMd(a));
  put(`harness/gemini/agents/${a.name}.md`, geminiMd(a));
  put(`harness/cursor/agents/${a.name}.md`, cursorMd(a));
}
put("harness/README.md", harnessReadme(agents));

// Stale output: generated files with no source agent.
const stale = [];
for (const h of ["codex", "opencode", "gemini", "cursor"]) {
  const dir = join(HARNESS, h, "agents");
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir).sort()) {
    const rel = `harness/${h}/agents/${f}`;
    if (!expected.has(rel)) stale.push(rel);
  }
}
if (existsSync(EVE)) {
  const names = new Set(agents.map((a) => a.name));
  for (const d of readdirSync(EVE, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()) {
    if (names.has(d)) continue;
    for (const f of ["agent.ts", "instructions.md"]) {
      const p = join(EVE, d, f);
      if (existsSync(p) && lf(readFileSync(p, "utf8")).split("\n", 1)[0].includes(GEN)) stale.push(relative(ROOT, p).split("\\").join("/"));
    }
  }
}

// ---------------------------------------------------------------- check / write

const changed = [];
for (const [rel, content] of [...expected].sort(([x], [y]) => (x < y ? -1 : 1))) {
  const p = join(ROOT, rel);
  const raw = existsSync(p) ? readFileSync(p, "utf8") : null;
  const current = raw === null ? null : lf(raw);
  if (current === content) {
    // --check tolerates a CRLF checkout (core.autocrlf); a write still leaves LF on disk.
    if (!CHECK && raw !== content) writeFileSync(p, content, "utf8");
    continue;
  }
  changed.push(`${current === null ? "missing" : "stale  "} ${rel}`);
  if (!CHECK) {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content, "utf8");
  }
}
for (const rel of stale) {
  changed.push(`orphan  ${rel}`);
  if (!CHECK) {
    const p = join(ROOT, rel);
    rmSync(p);
    try {
      rmdirSync(dirname(p));
    } catch {}
  }
}

if (CHECK) {
  if (changed.length) {
    console.error(`build-agents: ${changed.length} generated file(s) out of date with agents/*.md:`);
    for (const c of changed) console.error(`  ${c}`);
    console.error("Run `npm run build:agents` and commit the result.");
    process.exit(1);
  }
  console.log(`build-agents: ${agents.length} agents, ${expected.size} generated files, all current.`);
} else {
  for (const c of changed) console.log(`  ${c}`);
  console.log(`build-agents: ${agents.length} agents -> ${expected.size} files (${changed.length} written or removed).`);
}
if (kept.length) console.log(`build-agents: kept hand-written: ${kept.join(", ")}`);
